const SR=(r,b)=>b===0?"—":((r/b)*100).toFixed(1);

const RR=(r,b)=>b===0?"—":((r/(b/6))||0).toFixed(2);

const fmtOv=b=>`${Math.floor(b/6)}.${b%6}`;

export { RR, SR, fmtOv };
